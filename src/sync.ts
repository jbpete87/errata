import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./util.ts";

const START = "<!-- errata:start (generated by `errata sync`; edits here are overwritten) -->";
const END = "<!-- errata:end -->";

interface Entry {
  package: string;
  version: string;
  card: string[];
}

const parse = (v: string) => v.split("-")[0].split(".").map(Number);
const lte = (a: string, b: string) => {
  const [x, y] = [parse(a), parse(b)];
  for (let i = 0; i < 3; i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) < (y[i] ?? 0);
  return true;
};

/** Version of a package as actually installed in the project, or null. */
function installedVersion(project: string, pkg: string, lock: any): string | null {
  const manifest = join(project, "node_modules", pkg, "package.json");
  if (existsSync(manifest)) return JSON.parse(readFileSync(manifest, "utf8")).version;
  return lock?.packages?.[`node_modules/${pkg}`]?.version ?? null;
}

export function pickModel(model?: string): string {
  const dir = join(ROOT, "registry");
  const models = existsSync(dir) ? readdirSync(dir).filter((d) => !d.startsWith(".")) : [];
  if (model) {
    if (!models.includes(model)) throw new Error(`No registry entries for ${model}. Have: ${models.join(", ") || "none"}`);
    return model;
  }
  if (models.length !== 1) throw new Error(`Pass --model. Registry has: ${models.join(", ") || "none"}`);
  return models[0];
}

/**
 * Cards that apply to a project: same major as the installed version and measured at or
 * before it, since a correction for a newer release may not be true of an older one.
 */
export function cardsFor(project: string, model: string): { entry: Entry; installed: string }[] {
  const lockFile = join(project, "package-lock.json");
  const lock = existsSync(lockFile) ? JSON.parse(readFileSync(lockFile, "utf8")) : null;
  const out: { entry: Entry; installed: string }[] = [];
  for (const pkgDir of readdirSync(join(ROOT, "registry", model))) {
    const entries = readdirSync(join(ROOT, "registry", model, pkgDir))
      .filter((f) => f.endsWith(".json"))
      .map((f) => JSON.parse(readFileSync(join(ROOT, "registry", model, pkgDir, f), "utf8")) as Entry);
    if (!entries.length) continue;
    const installed = installedVersion(project, entries[0].package, lock);
    if (!installed) continue;
    const best = entries
      .filter((e) => parse(e.version)[0] === parse(installed)[0] && lte(e.version, installed))
      .sort((a, b) => (lte(a.version, b.version) ? 1 : -1))[0];
    if (best?.card.length) out.push({ entry: best, installed });
  }
  return out.sort((a, b) => a.entry.package.localeCompare(b.entry.package));
}

export function renderBlock(model: string, cards: { entry: Entry; installed: string }[]): string {
  const sections = cards.map(({ entry }) => `### ${entry.package} (measured at ${entry.version})\n${entry.card.map((l) => `- ${l}`).join("\n")}`);
  return `${START}\n## Package corrections\n\nMistakes ${model} makes from memory with the versions installed here, each checked against the package's types.\n\n${sections.join("\n\n")}\n${END}`;
}

/** Insert, replace or remove the managed block. Returns the new file content, or null if nothing changes. */
export function applyBlock(existing: string | null, block: string | null): string | null {
  const text = existing ?? "";
  const a = text.indexOf(START), b = text.indexOf(END);
  let next: string;
  if (a >= 0 && b > a) {
    next = block ? text.slice(0, a) + block + text.slice(b + END.length) : (text.slice(0, a).trimEnd() + "\n" + text.slice(b + END.length).trimStart()).trimStart();
  } else if (block) {
    next = text.trim() ? `${text.trimEnd()}\n\n${block}\n` : `${block}\n`;
  } else {
    return null;
  }
  return next === text ? null : next;
}

export function sync(project: string, opts: { model?: string; file?: string; dryRun: boolean }) {
  if (!existsSync(join(project, "package.json"))) throw new Error(`${project} has no package.json`);
  const model = pickModel(opts.model);
  const cards = cardsFor(project, model);
  const name = opts.file ?? (["AGENTS.md", "CLAUDE.md"].find((f) => existsSync(join(project, f))) ?? "AGENTS.md");
  const target = join(project, name);
  const next = applyBlock(existsSync(target) ? readFileSync(target, "utf8") : null, cards.length ? renderBlock(model, cards) : null);
  for (const { entry, installed } of cards) console.log(`  ${entry.package}@${installed}: ${entry.card.length} lines (measured at ${entry.version})`);
  if (!cards.length) console.log("  no cards match the installed packages");
  if (next === null) console.log(`${name}: up to date`);
  else if (opts.dryRun) console.log(`${name}: would be updated (dry run)`);
  else { writeFileSync(target, next); console.log(`${name}: updated`); }
}
